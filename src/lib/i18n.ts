export function zh(value: ReactNode): ReactNode {
  if (typeof value !== "string") return value;
  return dictionary[value] ?? value;
}

export function zhText(value: string) {
  return dictionary[value] ?? value;
}

export function zhNode(value: ReactNode): ReactNode {
  if (typeof value === "string") return zhText(value);
  if (Array.isArray(value)) return Children.map(value, (item) => zhNode(item));
  if (!isValidElement(value)) return value;
  const props = value.props as { children?: ReactNode };
  return cloneElement(value as ReactElement<{ children?: ReactNode }>, {
    ...props,
    children: props.children ? Children.map(props.children, (child) => zhNode(child)) : props.children,
  });
}
